#!/usr/bin/env bash

# -----------------------------------------------------------------------------
# ---------------------- Start display color correction -----------------------
# -----------------------------------------------------------------------------
set -euo pipefail

cd "$(dirname "$0")"


# -----------------------------------------------------------------------------
# ----------------------------------- Build -----------------------------------
# -----------------------------------------------------------------------------
if ! make -q; then
    make
fi


# -----------------------------------------------------------------------------
# ------------------------------- Stop Existing -------------------------------
# -----------------------------------------------------------------------------
if pgrep -x fix_disp_color >/dev/null; then
    pkill -TERM -x fix_disp_color
    for _ in $(seq 1 30); do
        pgrep -x fix_disp_color >/dev/null || break
        sleep 0.1
    done
fi


# -----------------------------------------------------------------------------
# ------------------------------------ Run ------------------------------------
# -----------------------------------------------------------------------------
exec ./fix_disp_color --profile ./profiles.conf
